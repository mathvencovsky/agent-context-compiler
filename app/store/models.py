"""SQLAlchemy 2 models for the persistence layer — M5 (SPEC §7).

Two tables back the resolve/get-document endpoints:

- ``sources`` — one row per normalized URL. ``id`` holds the ``doc_`` document
  id. ``current_version_id`` points at the latest persisted version; the FK is
  created with ``use_alter=True`` because ``sources`` and ``document_versions``
  reference each other (a cycle Alembic/DDL must break with a deferred
  ``ALTER TABLE``).
- ``document_versions`` — one row per distinct content hash of a source. A
  ``(source_id, content_hash)`` unique constraint enforces dedup at the schema
  level; the resolve handler never creates a second version for an unchanged
  body.

``warnings`` is stored as JSONB (Postgres). ``status`` is a textual enum that is
``'ready'`` for the MVP (DECISIONS.md 2026-10-11); a version is only persisted
after a successful extraction. ``chunks`` (M6) backs lexical + vector search;
api_keys/usage_events belong to M9 and are intentionally absent here.

The ``chunks`` table (SPEC §7, M6) stores one indexed chunk per row. Its ``tsv``
column is a Postgres GENERATED column (``to_tsvector('simple', text)``) — the
app NEVER writes it; it is mapped read-only so Alembic's ``target_metadata``
stays coherent. ``embedding`` is a pgvector ``vector(1536)`` column; 1536 is
``EMBEDDING_DIM`` (DECISIONS.md 2026-10-12 — text-embedding-3-small).
"""

from __future__ import annotations

from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import Computed, ForeignKey, UniqueConstraint, func
from sqlalchemy.dialects import postgresql
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    """Declarative base shared by all M5 models."""


class Source(Base):
    """A fetched source, keyed by its normalized URL (SPEC §7)."""

    __tablename__ = "sources"

    # Holds the doc_... document_id (make_document_id of the normalized URL).
    id: Mapped[str] = mapped_column(primary_key=True)
    url_normalized: Mapped[str] = mapped_column(unique=True, index=True)
    domain: Mapped[str] = mapped_column(index=True)
    current_version_id: Mapped[str | None] = mapped_column(
        ForeignKey("document_versions.id", use_alter=True),
    )
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class DocumentVersion(Base):
    """One version of one source, keyed by its ver_... id (SPEC §7)."""

    __tablename__ = "document_versions"
    __table_args__ = (UniqueConstraint("source_id", "content_hash"),)

    # Holds the ver_... version_id (make_version_id of the content hash).
    id: Mapped[str] = mapped_column(primary_key=True)
    source_id: Mapped[str] = mapped_column(ForeignKey("sources.id"), index=True)
    content_hash: Mapped[str] = mapped_column(index=True)
    fetched_at: Mapped[datetime] = mapped_column()
    etag: Mapped[str | None] = mapped_column()
    last_modified: Mapped[str | None] = mapped_column()
    render_mode: Mapped[str] = mapped_column()
    raw_blob_key: Mapped[str] = mapped_column()
    ir_blob_key: Mapped[str] = mapped_column()
    status: Mapped[str] = mapped_column(default="ready")
    warnings: Mapped[list[dict[str, object]]] = mapped_column(postgresql.JSONB)


#: Embedding dimensionality for the pgvector column (EMBEDDING_DIM; SPEC §5).
#: text-embedding-3-small produces 1536-dim vectors (DECISIONS.md 2026-10-12).
_EMBEDDING_DIM = 1536


class Chunk(Base):
    """One indexed chunk derived from a document version (SPEC §5, §7).

    Rows are written by the indexer (``app/index/indexer.py``) with a
    delete-then-insert strategy per ``version_id`` (idempotent). The ``tsv``
    column is GENERATED by Postgres from ``text`` and is mapped read-only — the
    app never writes it. ``embedding`` is a pgvector ``vector(1536)`` column
    (1536 = EMBEDDING_DIM). ``block_ids`` is always non-empty (provenance,
    CLAUDE.md).
    """

    __tablename__ = "chunks"

    id: Mapped[int] = mapped_column(primary_key=True)
    version_id: Mapped[str] = mapped_column(
        ForeignKey("document_versions.id"), index=True
    )
    block_ids: Mapped[list[str]] = mapped_column(postgresql.ARRAY(postgresql.TEXT))
    heading_path: Mapped[list[str]] = mapped_column(postgresql.ARRAY(postgresql.TEXT))
    text: Mapped[str] = mapped_column()
    md: Mapped[str] = mapped_column()
    tokens: Mapped[int] = mapped_column()
    ord: Mapped[int] = mapped_column()
    embedding: Mapped[list[float]] = mapped_column(Vector(_EMBEDDING_DIM))
    # Generated by Postgres (to_tsvector('simple', text)); read-only — the app
    # NEVER writes this column. Mapped so Alembic's target_metadata is coherent.
    tsv: Mapped[str | None] = mapped_column(
        postgresql.TSVECTOR,
        Computed("to_tsvector('simple', text)", persisted=True),
        nullable=True,
    )
